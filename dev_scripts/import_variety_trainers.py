"""Import the user's indexed artwork; never execute code from the asset archive."""
from pathlib import Path
import hashlib
import json
import sys
import zipfile

ROOT=Path(__file__).resolve().parents[1]

def append_after(file, anchor, addition):
    p=ROOT/file
    text=p.read_text()
    if addition.strip() in text:return
    assert text.count(anchor)==1,(file,anchor)
    p.write_text(text.replace(anchor,anchor+addition))

def main(pack):
    z=zipfile.ZipFile(pack)
    roster=json.loads(z.read('roster.json'))
    assert len(roster)==32 and len({r['id'] for r in roster})==32
    hashes={}
    for i,r in enumerate(roster):
        ident=r['id']; assert ident.isalpha()
        r['symbol']='Variety'+ident.title()
        r['index']=i
        for source,dest in [('battle.png',f'graphics/trainers/front_pics/variety_{ident}.png'),
                            ('battle.pal',f'graphics/trainers/palettes/variety_{ident}.pal'),
                            ('overworld.png',f'graphics/object_events/pics/people/variety_{ident}.png'),
                            ('overworld.pal',f'graphics/object_events/palettes/variety_{ident}.pal')]:
            data=z.read(f'trainers/{ident}/{source}')
            p=ROOT/dest;p.parent.mkdir(parents=True,exist_ok=True);p.write_bytes(data)
            hashes[dest]=hashlib.sha256(data).hexdigest()
    target=ROOT/'data/trainer_variety';target.mkdir(parents=True,exist_ok=True)
    (target/'roster.json').write_text(json.dumps(roster,indent=2)+'\n')
    (target/'asset_manifest.json').write_text(json.dumps(hashes,indent=2)+'\n')
    append_after('include/constants/trainers.h','    TRAINER_PIC_CAST_ZURI,\n',''.join(f'    TRAINER_PIC_VARIETY_{r["id"].upper()},\n' for r in roster))
    append_after('include/constants/event_objects.h','    OBJ_EVENT_GFX_CAST_ZURI,\n',''.join(f'    OBJ_EVENT_GFX_VARIETY_{r["id"].upper()},\n' for r in roster))
    append_after('include/constants/event_objects.h','#define OBJ_EVENT_PAL_TAG_CAST_ZURI 0x7C09\n',''.join(f'#define OBJ_EVENT_PAL_TAG_VARIETY_{r["id"].upper()} 0x{0x7d00+r["index"]:04X}\n' for r in roster))
    graphics=[];ow=[];pics=[];info=[];ptrs=[];pals=[];fronts=[]
    for r in roster:
        ident=r['id'];s=r['symbol'];u=ident.upper()
        graphics += [f'const u32 gTrainerFrontPic_{s}[] = INCGFX_U32("graphics/trainers/front_pics/variety_{ident}.png", ".4bpp.smol");',
                     f'const u16 gTrainerPalette_{s}[] = INCGFX_U16("graphics/trainers/palettes/variety_{ident}.pal", ".gbapal");']
        fronts.append(f'    [TRAINER_PIC_VARIETY_{u}] = {{ .frontPic = TRAINER_FRONT_PIC(gTrainerFrontPic_{s}, gTrainerPalette_{s}), }},')
        ow += [f'const u32 gObjectEventPic_{s}[] = INCGFX_U32("graphics/object_events/pics/people/variety_{ident}.png", ".4bpp", "-mwidth 2 -mheight 4");',
               f'const u16 gObjectEventPal_{s}[] = INCGFX_U16("graphics/object_events/palettes/variety_{ident}.pal", ".gbapal");']
        pics.append(f'static const struct SpriteFrameImage sPicTable_{s}[] = {{ overworld_ascending_frames(gObjectEventPic_{s}, 2, 4), }};')
        info.append(f'''const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_{s} = {{
    .tileTag = TAG_NONE, .paletteTag = OBJ_EVENT_PAL_TAG_VARIETY_{u},
    .reflectionPaletteTag = OBJ_EVENT_PAL_TAG_NONE, .size = 256,
    .width = 16, .height = 32, .paletteSlot = PALSLOT_NPC_SPECIAL,
    .shadowSize = SHADOW_SIZE_M, .inanimate = FALSE, .compressed = FALSE,
    .tracks = {'TRACKS_NONE' if ident=='fen' else 'TRACKS_FOOT'},
    .oam = &gObjectEventBaseOam_16x32, .subspriteTables = sOamTables_16x32,
    .anims = sAnimTable_Standard, .images = sPicTable_{s},
}};''')
        ptrs.append(f'    [OBJ_EVENT_GFX_VARIETY_{u}] = &gObjectEventGraphicsInfo_{s},')
        pals.append(f'    {{gObjectEventPal_{s}, OBJ_EVENT_PAL_TAG_VARIETY_{u}}},')
    for path,lines in [('src/data/graphics/variety_trainers.h',graphics),('src/data/object_events/variety_graphics.h',ow),
                       ('src/data/object_events/variety_pic_tables.h',pics),('src/data/object_events/variety_graphics_info.h',info)]:
        (ROOT/path).write_text('// Generated by import_variety_trainers.py\n'+'\n'.join(lines)+'\n')
    append_after('src/data/graphics/trainers.h','const struct TrainerPicInfo gTrainerPicInfo[TRAINER_PIC_COUNT] =\n{\n','\n'.join(fronts)+'\n')
    p=ROOT/'src/data/graphics/trainers.h';s=p.read_text();anchor='const struct TrainerPicInfo gTrainerPicInfo[TRAINER_PIC_COUNT]'
    if '#include "variety_trainers.h"' not in s:p.write_text(s.replace(anchor,'#include "variety_trainers.h"\n\n'+anchor))
    for file,inc in [('object_event_graphics.h','variety_graphics.h'),('object_event_pic_tables.h','variety_pic_tables.h'),('object_event_graphics_info.h','variety_graphics_info.h')]:
        p=ROOT/'src/data/object_events'/file;s=p.read_text()
        if f'#include "{inc}"' not in s:p.write_text(s+f'\n#include "{inc}"\n')
    append_after('src/data/object_events/object_event_graphics_info_pointers.h','extern const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_CastZuri;\n',''.join(f'extern const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_{r["symbol"]};\n' for r in roster))
    append_after('src/data/object_events/object_event_graphics_info_pointers.h','    [OBJ_EVENT_GFX_CAST_ZURI] = &gObjectEventGraphicsInfo_CastZuri,\n','\n'.join(ptrs)+'\n')
    append_after('src/event_object_movement.c','    {gObjectEventPal_CastZuri, OBJ_EVENT_PAL_TAG_CAST_ZURI},\n','\n'.join(pals)+'\n')
    print('Registered 32 walking sprites, battle portraits, and exact shared palettes.')

if __name__=='__main__':main(sys.argv[1])
