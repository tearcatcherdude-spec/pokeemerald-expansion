"""Build exact-message bindings and a reviewable source/reply manifest."""
from pathlib import Path
import hashlib, json, re
from build_cast import ctext, EXPRESSIONS
from companion_context_content import ROWS

ROOT = Path(__file__).resolve().parents[1]
VOICES = ['pip', 'silas', 'kade', 'ashe', 'nico', 'riven', 'emi', 'vera', 'lume', 'mochi', 'zuri']

def global_c_text_blocks():
    """Inventory exported C strings referenced by script msgbox operands.

    Conditional compilation and native formatting still require review. Static
    C strings cannot be exported merely by writing an assembly .global alias.
    """
    found={}
    pattern=re.compile(r'^const\s+u8\s+(\w+)\s*\[\s*\]\s*=\s*(?:_|COMPOUND_STRING)\(\s*((?:"(?:\\.|[^"\\])*"\s*)+)\)\s*;',re.M)
    for path in sorted((ROOT/'src').rglob('*.c')):
        for m in pattern.finditer(path.read_text(encoding='utf-8')):
            raw=''.join(re.findall(r'"((?:\\.|[^"\\])*)"',m[2]))
            found[m[1]]=dict(path=path.relative_to(ROOT).as_posix(),text=raw,
                sha256=hashlib.sha256(raw.encode()).hexdigest(),source_kind='c_global',
                compilation_eligibility='requires_review')
    return found

def text_blocks():
    found = {}
    # Imported sources supersede the unused vanilla FRLG copies.
    paths = sorted((ROOT/'data/maps').rglob('scripts.inc'))
    paths += sorted((ROOT/'data/text').rglob('*.inc'))
    paths += sorted((ROOT/'data/scripts').rglob('*.inc'))
    paths += sorted((ROOT/'data/kanto').rglob('*.inc'))
    paths += sorted((ROOT/'data/cast').rglob('*.inc'))
    paths += sorted((ROOT/'data/bonds').rglob('*.inc'))
    paths += [ROOT/'data/event_scripts.s']
    for path in paths:
        text = path.read_text(encoding='utf-8')
        for m in re.finditer(r'^(\w+)::?[^\n]*\n((?:[ \t]*\.string[^\n]*\n)+)', text, re.M):
            raw = ''.join(re.findall(r'\.string\s+"(.*)"', m[2]))
            found[m[1]] = dict(path=path.relative_to(ROOT).as_posix(),
                               text=raw, sha256=hashlib.sha256(raw.encode()).hexdigest())
        # Some single text addresses have assembler-selected wording (the
        # four-/six-stage Berry descriptions, for example). Preserve the whole
        # conditional source for review and drift detection; never pretend both
        # alternatives are one displayed sentence or infer a completed outcome.
        conditional = r'^(\w+)::?[^\n]*\n([ \t]*\.if[^\n]*\n(?:[ \t]*\.(?:if|else|elseif|endif|string)\b[^\n]*\n)+)'
        for m in re.finditer(conditional, text, re.M):
            variants = re.split(r'^[ \t]*\.(?:else|elseif)\b[^\n]*$', m[2], flags=re.M)
            found[m[1]] = dict(path=path.relative_to(ROOT).as_posix(),
                text=''.join(re.findall(r'\.string\s+"(.*)"', m[2])),
                sha256=hashlib.sha256(m[2].encode()).hexdigest(),
                source_kind='asm_conditional', conditional_assembly=m[2],
                source_variants=[''.join(re.findall(r'\.string\s+"(.*)"', v)) for v in variants],
                compilation_eligibility='requires_review')
    found.update(global_c_text_blocks())
    return found

def build():
    blocks = text_blocks()
    output = ['// Generated by build_companion_contexts.py; append-only context IDs.']
    review = []; bindings = []; labels = set()
    for context, row in enumerate(ROWS):
        assert context < 12288
        records = []
        for label in row['labels']:
            assert label not in labels and label in blocks, label
            labels.add(label); bindings.append((label, context))
            output.append(f'extern const u8 {label}[];')
        for voice, raw in zip(VOICES, row['replies']):
            emotion, text = raw.split('~', 1) if '~' in raw else ('neutral', raw)
            assert emotion in EXPRESSIONS
            records.append(dict(voice=voice, expression=emotion, text=text))
        review.append(dict(id=context, key=row['key'], subject=row['subject'],
                           sources={n:blocks[n] for n in row['labels']}, replies=records))
        if row.get('retired'):
            review[-1].update(retired=row['retired'], retired_sources={n:blocks[n] for n in row['retired_sources']})
    output += ['static const struct ContextReply sContextReplies[][COMPANION_VOICE_COUNT] = {']
    for row in review:
        output.append(' { // '+str(row['id'])+' '+row['key'])
        for reply in row['replies']:
            output.append('  {NULL, 0},' if row.get('retired') else '  {'+ctext(reply['text'], reply['voice'])+', '+str(EXPRESSIONS.index(reply['expression']))+'},')
        output.append(' },')
    output += ['};', 'static const struct ContextMessage sContextMessages[] = {']
    output += [f' {{{label}, {context}}},' for label,context in bindings]
    output += ['};']
    (ROOT/'src/data/companion_contexts.h').write_text('\n'.join(output)+'\n', encoding='utf-8')
    (ROOT/'data/scripts/companion_context_exports.inc').write_text(
        '@ Exact NPC text addresses are referenced by the reaction catalogue.\n'+
        '\n'.join(f'\t.global {label}' for label,_ in bindings)+'\n', encoding='utf-8')
    folder=ROOT/'data/companion_dialogue';folder.mkdir(exist_ok=True)
    (folder/'contexts.json').write_text(json.dumps(dict(voices=VOICES, capacity=12288, legacy_capacity=736, contexts=review), indent=2)+'\n', encoding='utf-8')
    active=sum(not r.get('retired') for r in review)
    print(f'Built {active} active contexts ({len(review)} reserved IDs), {len(bindings)} exact message labels, {11*active} authored replies.')

if __name__ == '__main__': build()
