"""Compile the reviewable offline lesson catalogue; --check detects stale output."""
from pathlib import Path
import json,sys,re
ROOT=Path(__file__).resolve().parents[1]
def build():
    data=json.loads((ROOT/'data/roaming_tutor/lessons.json').read_text())
    constants=(ROOT/'include/constants/moves.h').read_text();gen4=constants[:constants.index('MOVES_COUNT_GEN4')]
    out=['// Generated by build_roaming_tutor_catalog.py; edit lessons.json.']
    names={'general':'sGeneralLessons','beldum_family':'sMetalLessons','magikarp':'sFishLessons'}
    for key,name in names.items():
        out.append(f'static const struct TutorLesson {name}[] = {{')
        seen=set()
        for row in data[key]:
            move=row['move'];assert re.fullmatch('[A-Z_]+',move) and 'MOVE_'+move in gen4
            assert move not in seen and 5<=row['level']<=100;seen.add(move)
            trait='0' if row['trait']=='ANY' else 'TUTOR_'+row['trait']
            out.append(f'    LESSON({move}, {row["level"]}, {trait}, {json.dumps(row["reason"])}),')
        out.append('};')
    return '\n'.join(out)+'\n'
if __name__=='__main__':
    target=ROOT/'src/data/roaming_tutor_lessons.h';text=build()
    if '--check' in sys.argv:assert target.read_text()==text,'Tutor lesson header is stale'
    else:target.write_text(text)
    print('PASS: species-aware Gen I-IV lesson catalogue is current')
