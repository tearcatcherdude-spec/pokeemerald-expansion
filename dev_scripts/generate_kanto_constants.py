from pathlib import Path
import ast,re,json
ROOT=Path(__file__).resolve().parents[1]

def definitions(path):
 out={}
 for line in path.read_text(encoding='utf-8').splitlines():
  m=re.match(r'^#define\s+(\w+)\s+(.+)',line)
  if m:out[m[1]]=m[2].split('//')[0].strip()
 return out

def resolve(defs,extra):
 known=dict(extra)
 def value(node):
  if isinstance(node,ast.Constant) and isinstance(node.value,int):return node.value
  if isinstance(node,ast.Name):return known[node.id]
  if isinstance(node,ast.UnaryOp) and isinstance(node.op,ast.USub):return -value(node.operand)
  if isinstance(node,ast.BinOp):
   a,b=value(node.left),value(node.right)
   if isinstance(node.op,ast.Add):return a+b
   if isinstance(node.op,ast.Sub):return a-b
   if isinstance(node.op,ast.Mult):return a*b
   if isinstance(node.op,ast.Div) or isinstance(node.op,ast.FloorDiv):return a//b
   if isinstance(node.op,ast.LShift):return a<<b
   if isinstance(node.op,ast.RShift):return a>>b
   if isinstance(node.op,ast.BitOr):return a|b
   if isinstance(node.op,ast.BitAnd):return a&b
  raise ValueError('Not an integer constant')
 for _ in range(len(defs)+1):
  changes=0
  for k,expr in defs.items():
   if k in known:continue
   try:known[k]=value(ast.parse(expr,mode='eval').body);changes+=1
   except (ValueError,SyntaxError,KeyError,ZeroDivisionError):pass
  if not changes:break
 return {k:v for k,v in known.items() if k in defs}

def generate():
 common={'MAX_TRAINERS_COUNT':768,'VARS_START_FRLG':0x4000,'TEMP_FLAGS_START':0}
 common.update({f'FLAG_TEMP_{i:X}':i for i in range(1,32)})
 flags=resolve(definitions(ROOT/'include/constants/flags_frlg.h'),common)
 variables=resolve(definitions(ROOT/'include/constants/vars_frlg.h'),common)
 trainers=resolve(definitions(ROOT/'include/constants/opponents_frlg.h'),{})
 lines=['// Generated by dev_scripts/generate_kanto_constants.py; original IDs stay unchanged.','#ifndef GUARD_CONSTANTS_KANTO_SYMBOLS_H','#define GUARD_CONSTANTS_KANTO_SYMBOLS_H','#include "constants/kanto_progress.h"','']
 renamed={}
 for name,n in sorted(flags.items()):
  if not name.startswith('FLAG_'):continue
  new='KANTO_'+name
  if n<32:expr=hex(n)
  elif n<0x900:expr=f'(KANTO_FLAG_BASE + 0x{n:03X})'
  elif 0x4000<=n<0x4080:expr=hex(n) # Shared transient engine controls.
  else:continue
  lines.append(f'#define {new} {expr}');renamed[name]=new
 for name,n in sorted(variables.items()):
  if not name.startswith('VAR_'):continue
  new='KANTO_'+name
  if 0x4000<=n<0x4020 or 0x8000<=n<0x8020:expr=hex(n)
  elif 0x4020<=n<0x4100:expr=f'(KANTO_VAR_BASE + 0x{n-0x4000:02X})'
  else:continue
  lines.append(f'#define {new} {expr}');renamed[name]=new
 for name,n in sorted(trainers.items()):
  if not name.startswith('TRAINER_') or n>=624:continue
  new='KANTO_'+name;expr='0' if n==0 else f'(KANTO_TRAINER_BASE + {n})'
  lines.append(f'#define {new} {expr}');lines.append(f'#define TRAINER_KANTO_DATA_{name[8:]} {n}');renamed[name]=new
 lines+=['','#endif','']
 (ROOT/'include/constants/kanto_symbols.h').write_text('\n'.join(lines),encoding='utf-8',newline='\n')
 out=ROOT/'data/kanto';out.mkdir(exist_ok=True)
 (out/'symbol_manifest.json').write_text(json.dumps({'renamed':renamed,'native_flags':flags,'native_vars':variables,'native_trainers':trainers},indent=2)+'\n',encoding='utf-8',newline='\n')
 print(f'Generated {len(renamed)} isolated Kanto script symbols')

if __name__=='__main__':generate()
