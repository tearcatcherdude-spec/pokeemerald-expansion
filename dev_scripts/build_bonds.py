"""Build append-only bond content; never alter existing map events or terrain."""
import json, pathlib, struct, textwrap, re
from bond_scenes import TASKS, GIFTS, GIFT_REPLIES, REWARDS, CHALLENGES, NEIGHBOR_QUESTIONS
from bond_teams import TEAMS, EVOLUTIONS
ROOT = pathlib.Path(__file__).resolve().parents[1]
NAMES = ['silas','kade','ashe','nico','riven','emi','vera','lume','mochi','zuri']
def load(p): return json.loads((ROOT/p).read_text(encoding='utf-8'))
def write(p,s):
    p=ROOT/p; p.parent.mkdir(parents=True,exist_ok=True); p.write_text(s,encoding='utf-8')
def ct(s):
    s=s.replace('Pokémon','POKEMON').replace('’',"'").replace('“','"').replace('”','"').replace('—','-')
    lines=[]
    for paragraph in s.split('\n'): lines += textwrap.wrap(paragraph,32,break_long_words=False,break_on_hyphens=False) or ['']
    text=lines[0]+''.join(('\\n' if i==1 else '\\l')+line for i,line in enumerate(lines[1:],1))+'$'
    return 'COMPOUND_STRING("'+text.replace('"','\\"')+'")'
def short(s): return 'COMPOUND_STRING('+json.dumps(s+'$')+')'

def place(events):
    layouts={l['id']:l for l in load('data/layouts/layouts.json')['layouts']}
    cache={}
    for e in events:
        m=load(f'data/maps/{e["map_folder"]}/map.json'); layout=layouts[m['layout']]
        description=e['meeting_point']
        if 'Contest Hall' in description:
            description=description.replace('Contest Hall','Battle Tent')
            e['meeting_point']=description
        token=next((t for word,t in [('Pokémon Center','POKEMON_CENTER'),('Devon','DEVON_CORP'),('Oceanic','OCEANIC_MUSEUM'),('Department','DEPARTMENT_STORE'),('Lilycove Museum','LILYCOVE_MUSEUM'),('Battle Tent','BATTLE_TENT'),('Pretty Petal','PRETTY_PETAL'),('Fan Club','POKEMON_FAN_CLUB'),('Museum','MUSEUM'),('Shipyard','SHIPYARD'),('Bike Shop','BIKE_SHOP'),('Gym','_GYM')] if word in description),None)
        key=e['map_folder'],token
        if key not in cache:
            warp=next((w for w in m['warp_events'] if token and token in w['dest_map']),None)
            if warp: ax,ay=warp['x'],warp['y']+1
            else:
                assert 'outdoor market' in description
                ax,ay=8,30
            raw=(ROOT/layout['blockdata_filepath']).read_bytes(); width,height=layout['width'],layout['height']
            grid=struct.unpack('<'+'H'*(len(raw)//2),raw)
            occupied=set()
            for obj in m['object_events']:
                rx,ry=obj.get('movement_range_x',0),obj.get('movement_range_y',0)
                for dx in range(-rx,rx+1):
                    for dy in range(-ry,ry+1): occupied.add((obj['x']+dx,obj['y']+dy))
            for kind in ['warp_events','coord_events','bg_events']:
                occupied.update((v['x'],v['y']) for v in m.get(kind,[]))
            def free(x,y): return 0<=x<width and 0<=y<height and not grid[y*width+x]&0xC00 and (x,y) not in occupied
            # Keep the doorway column clear. Require a broad approachable patch.
            candidates=[(x,y) for y in range(ay, min(ay+6,height)) for x in range(max(0,ax-5),min(ax+6,width)) if abs(x-ax)>=2 and free(x,y) and sum(free(x+dx,y+dy) for dx,dy in [(0,1),(0,-1),(1,0),(-1,0)])>=3]
            assert candidates,(key,ax,ay)
            x,y=min(candidates,key=lambda p:abs(p[0]-(ax+2))+abs(p[1]-(ay+1)))
            cache[key]={'x':x,'y':y,'elevation':grid[y*width+x]>>12,'landmark_approach':[ax,ay]}
        e['marker_tile']=cache[key]
        # These are placements awaiting native route/screenshot checks, never a
        # claim that a collision-bit check substitutes for game validation.
        e['status']='PLACED_PENDING_NATIVE_VALIDATION'
        e['marker_instruction']=f'Heart marker {abs(e["marker_tile"]["x"]-e["marker_tile"]["landmark_approach"][0])} tiles '+('east' if e['marker_tile']['x']>=e['marker_tile']['landmark_approach'][0] else 'west')+' of the entrance approach.'
    return events

def main():
    events=place(load('data/bonds/bond-events-draft.json')['events'])
    events=sorted(events,key=lambda e:(NAMES.index(e['character'].lower()),e['stage']))
    maps=list(dict.fromkeys(e['map_folder'] for e in events))
    result={'baseline_commit':'abca44ff33711c59df08e0734d41e658263c6128','status':'IN_DEVELOPMENT','events':events,'destination_maps':maps}
    write('data/bonds/events.json',json.dumps(result,indent=2)+'\n')
    out=['// Generated by dev_scripts/build_bonds.py.\nstatic const struct BondEvent sBondEvents[50] = {\n']
    for e in events:
        tile=e['marker_tile'];out.append('    {.map = '+e['map_id']+f', .x = {tile["x"]}, .y = {tile["y"]}, .destination = {maps.index(e["map_folder"])}, .title = '+ct(e['title'])+', .directions = '+ct(e['region']+' -> '+e['location_name']+'\n'+e['meeting_point']+'. '+e['marker_instruction'])+', .objective = '+ct(e['objective'])+'},\n')
    out.append('};\n')
    out.append('static const struct BondCenter sBondCenters[] = {\n')
    for p in sorted((ROOT/'data/maps').glob('*/map.json')):
        m=json.loads(p.read_text(encoding='utf-8'))
        if m.get('map_type') not in ['MAP_TYPE_TOWN','MAP_TYPE_CITY','MAP_TYPE_ROUTE']: continue
        for w in m.get('warp_events',[]):
            if 'POKEMON_CENTER_1F' in w['dest_map']:
                out.append('    {'+m['id']+f', {w["x"]}, {w["y"]+1}'+'},\n')
    out.append('};\n')
    write('src/data/bond_events.h',''.join(out))
    scenes=[]
    out=['// Generated from authored dev_scripts/bond_scenes.py.\nstatic const struct BondScene sBondScenes[50] = {\n']
    for name in NAMES:
        assert len(TASKS[name])==5
        for stage,task in enumerate(TASKS[name]):
            intro,a,b,ra,rb,ending=task
            questions=['How would you like to respond?']
            options=[[a,b]]; responses=[[ra,rb]]
            if stage==2:
                options=[['I would like a date',"I'm glad we're friends","I'm not sure yet"]]
                responses=[[ra,rb,'There is no deadline. We can enjoy today and talk again when you want to.']]
            elif stage==4:
                questions=['Only one committed romance at a time. What do you both want?']
                options=[['Commit together','Stay close friends','Take more time']]
                responses=[[ra,rb,'We can take more time. The invitation will still be here.']]
            elif stage==3:
                for q,c,d,rc,rd in CHALLENGES[name]:
                    questions.append(q); options.append([c,d]); responses.append([rc,rd])
            elif name=='zuri' and stage==1:
                for q,c,d,rc,rd in NEIGHBOR_QUESTIONS:
                    questions.append(q); options.append([c,d]); responses.append([rc,rd])
            expression=[7,0,3,0,1][stage]
            row={'character':name,'stage':stage+1,'intro':intro,'questions':questions,'options':options,'responses':responses,'ending':ending,'expression':expression}
            scenes.append(row)
            arr=lambda values:'{'+', '.join(ct(v) for v in values)+'}'
            out.append('    {.intro = '+ct(name.upper()+': '+intro)+', .questions = '+arr(questions)+', .options = {'+', '.join(arr(v) for v in options)+'}, .responses = {'+', '.join(arr([name.upper()+': '+v for v in values]) for values in responses)+'}, .ending = '+ct(name.upper()+': '+ending)+f', .rounds = {len(options)}, .expression = {expression}'+'},\n')
    out.append('};\nstatic const struct BondGift sBondGifts[10][3] = {\n')
    for name in NAMES: out.append('    {'+', '.join('{ITEM_'+item+f', {value}'+'}' for item,value in GIFTS[name])+'},\n')
    out.append('};\nstatic const u8 *const sBondGiftReplies[10] = {\n')
    out.extend('    '+ct(name.upper()+': '+GIFT_REPLIES[name])+',\n' for name in NAMES)
    out.append('};\nstatic const u16 sBondRewardMoves[10][2] = {\n')
    for name in NAMES: out.append('    {MOVE_'+REWARDS[name][0]+', MOVE_'+REWARDS[name][1]+'},\n')
    out.append('};\nstatic const u8 *const sBondKeepsakes[10] = {\n')
    out.extend('    '+ct(REWARDS[name][2])+',\n' for name in NAMES)
    out.append('};\n')
    write('src/data/bond_scenes.h',''.join(out))
    write('data/bonds/dialogue_review.json',json.dumps({'scenes':scenes,'gifts':GIFTS,'gift_replies':GIFT_REPLIES,'rewards':REWARDS},indent=2)+'\n')
    party=(ROOT/'src/data/trainers_kanto.party').read_text(encoding='utf-8').split('\n=== TRAINER_KANTO_DATA_BOND_')[0].rstrip()+'\n'
    constants=(ROOT/'include/constants/kanto_progress.h').read_text(encoding='utf-8')
    constants=re.sub(r'#define KANTO_TRAINER_COUNT \d+','#define KANTO_TRAINER_COUNT 674',constants)
    constants=constants.split('// Bond trial trainers')[0].replace('\n#endif\n','\n').rstrip()+'\n\n// Bond trial trainers: appended after all 634 released native/cast entries.\n'
    review=[]
    previews=[]
    for who,name in enumerate(NAMES):
        character_previews=[]
        for band,level in enumerate([40,50,60,70]):
            symbol=f'TRAINER_KANTO_DATA_BOND_{name.upper()}_{level}'
            constants+=f'#define {symbol} {634+who*4+band}\n'
            gender='Male' if who<5 else 'Female'
            party+=f'\n=== {symbol} ===\nName: {name.upper()}\nClass: Pkmn Trainer 1\nPic: Cast {name.title()}\nGender: {gender}\nMusic: {gender}\nDouble Battle: No\nAI: Check Bad Move / Try To Faint\n\n'
            members=[]
            for species,moves in TEAMS[name]:
                if level>=50: species=EVOLUTIONS.get(species,species)
                party+=f'{species}\nLevel: {level}\nIVs: 20 HP / 20 Atk / 20 Def / 20 SpA / 20 SpD / 20 Spe\n'+''.join('- '+m+'\n' for m in moves.split('/'))+'\n'
                members.append({'species':species,'moves':moves.split('/'),'level':level,'ivs':20,'evs':0,'held_item':None})
            review.append({'character':name,'level':level,'trainer_index':634+who*4+band,'team':members})
            text=f'{name.upper()} - Practice team Lv. {level}.\nFour POKEMON. IVs 20, no EVs or held items. Single battle, normal player levels. No money stake. Party and supplies recover after a loss.\n'
            for mon in members: text+=mon['species']+': '+', '.join(mon['moves'])+'.\n'
            text+='Stage four: same reward as its nonbattle challenge. Later training: ordinary battle EXP only, no Bond EXP or repeated items.'
            character_previews.append(ct(text))
        previews.append('    {'+', '.join(character_previews)+'},\n')
    write('src/data/trainers_kanto.party',party.rstrip()+'\n')
    write('include/constants/kanto_progress.h',constants+'\n#endif\n')
    write('data/bonds/trial_teams.json',json.dumps(review,indent=2)+'\n')
    write('src/data/bond_trial_previews.h','// Generated from the actual authored teams.\nstatic const u8 *const sBondTrialPreviews[10][4] = {\n'+''.join(previews)+'};\n')
    print(f'Built {len(events)} event destinations on {len(maps)} existing maps; no native map files changed.')
if __name__=='__main__': main()
